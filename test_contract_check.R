## test_contract_check.R -- check_dataset_contract() on a scratch copy of datasets/DEMO.db: the clean copy
## passes, and each injected defect makes the check FAIL with the right message. Writes only to temp files.
##   Rscript test_contract_check.R
suppressMessages({ library(DBI); library(RSQLite); source("t2_views.R"); source("t2_build_lib.R"); source("t2_test_helpers.R"); source("dataset_contract_check.R") })
demo <- file.path(Sys.getenv("T2_DATASETS_DIR", "datasets"), "DEMO.db")
if (!file.exists(demo)) demo <- "datasets/DEMO.db"

## a fresh copy of DEMO.db with `sqls` run on it; returns the check results (a data.frame)
run_with <- function(sqls = character(0), deep = TRUE) {
  f <- tempfile(fileext = ".db"); on.exit(unlink(f))
  stopifnot(file.copy(demo, f))
  con <- dbConnect(SQLite(), f); on.exit(dbDisconnect(con), add = TRUE, after = FALSE)
  for (s in sqls) dbExecute(con, s)
  check_dataset_contract(con, "DEMO", verbose = FALSE, deep = deep)
}
## TRUE when some FAIL row has `msg` in its detail (and optionally in its test name)
failed <- function(r, msg) any(r$results$status == "FAIL" & grepl(msg, paste(r$results$test, r$results$detail), fixed = TRUE))

cat("== clean copy ==\n")
r <- run_with()
ok(r$ok, "the unmodified DEMO.db passes (deep)")
ok(!any(r$results$status == "FAIL"), "no failing row on the clean copy")
ok(run_with(deep = FALSE)$ok, "the unmodified DEMO.db passes (deep = FALSE)")

cat("== injected defects ==\n")
r <- run_with("INSERT INTO tested SELECT * FROM tested LIMIT 1")
ok(!r$ok && failed(r, "duplicated key"), "duplicate tested row is rejected (duplicated key)")
r <- run_with("INSERT INTO samples SELECT * FROM samples LIMIT 1")
ok(!r$ok && failed(r, "samples.key: 1 duplicated"), "duplicate samples row is rejected")
r <- run_with("UPDATE samples SET key = NULL WHERE rowid = (SELECT MIN(rowid) FROM samples)")
ok(!r$ok && failed(r, "samples.key: 1 NULL"), "NULL samples.key is rejected")
r <- run_with("UPDATE tcgai SET samplekey = NULL WHERE rowid = (SELECT MIN(rowid) FROM tcgai)")
ok(!r$ok && failed(r, "NULL key"), "NULL tcgai.samplekey is rejected (deep)")
ok(run_with("UPDATE tcgai SET samplekey = NULL WHERE rowid = (SELECT MIN(rowid) FROM tcgai)", deep = FALSE)$ok,
   "... and is not scanned with deep = FALSE (the row scans are the deep part)")
r <- run_with("UPDATE tcgai SET samplekey = 99999 WHERE rowid = (SELECT MIN(rowid) FROM tcgai)")
ok(!r$ok && failed(r, "orphan samplekeys"), "orphan tcgai.samplekey is rejected (deep)")
r <- run_with("UPDATE tcgacati SET probekey = 99999 WHERE rowid = (SELECT MIN(rowid) FROM tcgacati)")
ok(!r$ok && failed(r, "orphan probekeys"), "orphan tcgacati.probekey is rejected (deep)")
r <- run_with("INSERT INTO tcgai SELECT * FROM tcgai LIMIT 1")
ok(!r$ok && failed(r, "duplicated (probekey, type, samplekey)"), "duplicate tcgai fact is rejected (deep)")
r <- run_with("UPDATE dataset_meta SET value = 'NoSuchVar' WHERE key = 'default_y'")
ok(!r$ok && failed(r, "default_y=NoSuchVar"), "default_y naming no variable is rejected")
r <- run_with("UPDATE dataset_meta SET value = 'cohort' WHERE key = 'default_x'")
ok(r$ok, "default_x = a virtual column (cohort) passes")
r <- run_with(c("UPDATE dataset_meta SET value = 'growth_media' WHERE key = 'sampletype_col'",
                "UPDATE dataset_meta SET value = 'NoSuchLevel' WHERE key = 'sampletype_levels'"))
ok(!r$ok && failed(r, "not in sampletype_levels"), "sampletype_levels missing the actual values is rejected")
r <- run_with(c("UPDATE dataset_meta SET value = 'growth_media' WHERE key = 'sampletype_col'",
                "UPDATE dataset_meta SET value = 'NoSuchLevel' WHERE key = 'normal_label'"))
ok(!r$ok && failed(r, "normal_label: NoSuchLevel"), "normal_label that is not a level is rejected")
r <- run_with("UPDATE dataset_meta SET value = 'NoSuchCohort' WHERE key = 'heme_values'")
ok(!r$ok && failed(r, "heme_values: NoSuchCohort"), "heme_values that is not a cohort level is rejected")
r <- run_with("DELETE FROM datatypes WHERE type = 'driver'")
ok(!r$ok && failed(r, "types without a datatypes row: driver"), "type without a datatypes row is rejected")
r <- run_with("UPDATE datatypes SET r_datatype = 'numeric' WHERE type = 'driver'")
ok(!r$ok && failed(r, "declared numeric but stored in tcgacati: driver"), "categorical type declared numeric is rejected")
r <- run_with("UPDATE tested SET value = 0 WHERE rowid = (SELECT MIN(rowid) FROM tested)")
ok(!r$ok && failed(r, "value is not 1"), "tested.value 0 is rejected")
r <- run_with("INSERT INTO probes(key, probe) VALUES (99999, 'NOT_IN_ALLPROBES')")
ok(!r$ok && failed(r, "absent from allprobes"), "probes row absent from allprobes is rejected")
r <- run_with("UPDATE dataset_meta SET value = '' WHERE key = 'title'")
ok(!r$ok && failed(r, "empty keys"), "empty title is rejected")
for (h in c("yes", "TRUE", "No", "0", "1", "false"))
  ok(run_with(sprintf("UPDATE dataset_meta SET value = '%s' WHERE key = 'hidden'", h))$ok, paste("hidden =", h, "passes"))
r <- run_with("UPDATE dataset_meta SET value = 'maybe' WHERE key = 'hidden'")
ok(!r$ok && failed(r, "hidden 'maybe'"), "hidden = maybe is rejected")

cat("== drop_t2_dataless_probes ==\n")
f <- tempfile(fileext = ".db"); stopifnot(file.copy(demo, f)); con <- dbConnect(SQLite(), f)
n0 <- dbGetQuery(con, "SELECT COUNT(*) n FROM allprobes")$n
invisible(dbExecute(con, "INSERT INTO probes(key, probe) VALUES (99999, 'NODATA_PROBE')")); invisible(dbExecute(con, "INSERT INTO allprobes(probe) VALUES ('NODATA_PROBE')"))
invisible(dbExecute(con, "INSERT INTO tcgai(samplekey, probekey, type, value) VALUES (1, NULL, 'expr', 1)"))   # a NULL probekey must not hide the delete
ok(drop_t2_dataless_probes(con) == 1, "a dataless probe is dropped although tcgai holds a NULL probekey")
ok(dbGetQuery(con, "SELECT COUNT(*) n FROM allprobes")$n == n0, "allprobes lost exactly that name")
ok(dbGetQuery(con, "SELECT COUNT(*) n FROM probes WHERE probe = 'NODATA_PROBE'")$n == 0, "probes lost it too")
ok(drop_t2_dataless_probes(con) == 0, "a second call removes nothing")
dbDisconnect(con); unlink(f)
cat("== dataset_meta.R: a write that breaks the contract is rolled back ==\n")
meta_cli <- function(...) { o <- suppressWarnings(system2(file.path(R.home("bin"), "Rscript"), shQuote(c("dataset_meta.R", ...)), stdout = TRUE, stderr = TRUE)); list(out = o, status = attr(o, "status") %||% 0L) }
`%||%` <- function(a, b) if (is.null(a)) b else a
mf <- tempfile(fileext = ".db"); stopifnot(file.copy(demo, mf))
before <- meta_cli("show", mf)$out
ok(meta_cli("set", mf, "hidden=yes")$status == 0, "set hidden=yes is accepted")
ok(meta_cli("set", mf, "hidden=1")$status == 0 && identical(meta_cli("show", mf)$out, before), "... and back to 1 restores the file's dataset_meta")
r <- meta_cli("set", mf, "default_y=NoSuchVar")
ok(r$status == 1 && any(grepl("default_y=NoSuchVar", r$out)), "set default_y=NoSuchVar exits 1 and prints the failing row")
ok(identical(meta_cli("show", mf)$out, before), "... and leaves dataset_meta unchanged")
r <- meta_cli("set", mf, "title=")
ok(r$status == 1 && identical(meta_cli("show", mf)$out, before), "set title= (empty) exits 1 and changes nothing")
## a file that already fails stays repairable one key at a time
bf <- tempfile(fileext = ".db"); stopifnot(file.copy(demo, bf))
bc <- dbConnect(SQLite(), bf); invisible(dbExecute(bc, "UPDATE dataset_meta SET value = 'NoSuchVar' WHERE key = 'default_y'")); dbDisconnect(bc)
r <- meta_cli("set", bf, "title=Fixed")
ok(r$status == 0 && any(grepl("already failing", r$out)), "an already failing file accepts an unrelated write (and warns about the old failure)")
r <- meta_cli("set", bf, "default_x=AlsoBad")
ok(r$status == 1 && any(grepl("AlsoBad", r$out)), "... and still refuses a write that adds a failure")
r <- meta_cli("set", bf, "default_y=GENE01")
ok(r$status == 0, "... and accepts the write that repairs it")
unlink(bf)
r <- meta_cli("type-fill", mf, "driver=na|zero")
ok(r$status != 0 && any(grepl("sparse", r$out)), "type-fill: a fill for a sparse type is refused")
pf <- tempfile(fileext = ".db"); pc <- dbConnect(SQLite(), pf); invisible(dbExecute(pc, "CREATE TABLE t(a)")); dbDisconnect(pc)
r <- meta_cli("set", pf, "title=x")
ok(r$status != 0 && any(grepl("not a T2 dataset", r$out)), "a file with no clinpheno table is refused")
r <- meta_cli("show", "/scratch/shinyusb/nothing.db")
ok(r$status != 0 && any(grepl("served path", r$out)), "a served path is refused")
unlink(c(mf, pf))

cat("== t2_refuse_served ==\n")
ok(inherits(try(t2_refuse_served("/scratch/shinyusb/T2-data/datasets/TCGA.db"), silent = TRUE), "try-error"), "/scratch/shinyusb refused")
ok(inherits(try(t2_refuse_served("/scratch/Docker/x/../y.db"), silent = TRUE), "try-error"), "/scratch/Docker refused (after normalization)")
ok(identical(t2_refuse_served("/tmp/ok.db"), "/tmp/ok.db"), "a scratch path passes")
Sys.setenv(T2_SERVED_ROOTS = "/srv/live:/data/served")
ok(inherits(try(t2_refuse_served("/data/served/a.db"), silent = TRUE), "try-error"), "a prefix from T2_SERVED_ROOTS is refused")
ok(identical(t2_refuse_served("/data/servedx/a.db"), "/data/servedx/a.db"), "... but only on a path boundary")
Sys.unsetenv("T2_SERVED_ROOTS")
cat("== sqlite_diff.R: a duplicated row is a change ==\n")
d1 <- tempfile(fileext = ".db"); d2 <- tempfile(fileext = ".db"); rp <- tempfile(fileext = ".md")
stopifnot(file.copy(demo, d1), file.copy(demo, d2))
cx <- dbConnect(SQLite(), d2); invisible(dbExecute(cx, "INSERT INTO tested SELECT * FROM tested LIMIT 1")); dbDisconnect(cx)
Sys.chmod(d1, "0444")
o <- suppressWarnings(system2(file.path(R.home("bin"), "Rscript"), shQuote(c("sqlite_diff.R", d1, d2, rp)), stdout = TRUE, stderr = TRUE))
rep <- readLines(rp)
ok(any(grepl("DIFFERENT", rep)) && any(grepl("^\\| tested .*changed", rep)), "two copies, one with a duplicated tested row: the report says changed")
ok(any(grepl("row counts differ", rep)), "... and names the row counts")
o <- suppressWarnings(system2(file.path(R.home("bin"), "Rscript"), shQuote(c("sqlite_diff.R", d1, d1, rp)), stdout = TRUE, stderr = TRUE))
ok(any(grepl("IDENTICAL", readLines(rp))), "a read-only file against itself: identical")
unlink(c(d1, d2, rp))
cat("== t2_download_lib.R: verified downloads ==\n")
source("t2_download_lib.R")
td <- tempfile(); dir.create(td); src <- file.path(td, "src.txt"); writeLines("hello", src)
man <- file.path(td, "m.sha256"); dest <- file.path(td, "out.txt"); u <- paste0("file://", src)
r <- try(t2_download_verified(u, dest, "out.txt", man), silent = TRUE)
ok(inherits(r, "try-error") && !file.exists(dest) && !file.exists(paste0(dest, ".part")), "a file with no manifest entry stops; nothing is left behind")
Sys.setenv(T2_RECORD_CHECKSUMS = "1"); t2_download_verified(u, dest, "out.txt", man); Sys.unsetenv("T2_RECORD_CHECKSUMS")
ok(file.exists(dest) && grepl("^[0-9a-f]{64}  out.txt$", readLines(man)), "T2_RECORD_CHECKSUMS=1 records the hash and renames")
unlink(dest); t2_download_verified(u, dest, "out.txt", man)
ok(file.exists(dest), "the next run verifies against the manifest")
writeLines("tampered", src); unlink(dest)
r <- try(t2_download_verified(u, dest, "out.txt", man), silent = TRUE)
ok(inherits(r, "try-error") && !file.exists(dest) && !file.exists(paste0(dest, ".part")), "a changed file (hash mismatch) stops; no .part, no dest")
writeLines("hello", src)
ok(inherits(try(t2_download_verified(u, dest, "out.txt", man, size = 999), silent = TRUE), "try-error"), "a size mismatch stops (was a warning)")
for (d in c("CPTAC", "TCGATARGETGTEX", "TCGA")) {
  mm <- .t2_manifest(file.path(d, "checksums.sha256")); there <- file.exists(file.path(d, "Data", names(mm)))
  ok(length(mm) > 0 && (!any(there) || all(vapply(names(mm)[there], function(n) tryCatch(t2_verify_checksum(file.path(d, "Data", n), n, file.path(d, "checksums.sha256")), error = function(e) FALSE), NA))),
     sprintf("%s: the manifest lists %d file(s) and every downloaded one verifies", d, length(mm)))
}
unlink(td, recursive = TRUE)
finish("test_contract_check")
